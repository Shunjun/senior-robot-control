"""Explicit bindings to the existing vehicle diagnostic owner; no implementation copy."""

import asyncio
from collections.abc import Callable, Hashable
from dataclasses import dataclass
from typing import Protocol

from vehicle_manager.vehicle_logs.models import LogPage


class QueueCounter(Protocol):
    def enqueue(self, key: Hashable, now: float) -> None: ...
    def start(self, key: Hashable, now: float) -> None: ...
    def finish(self, key: Hashable, now: float) -> None: ...
    def reject(self, now: float, count: int = 1) -> None: ...


class SubscriptionQueue(Protocol):
    def qsize(self) -> int: ...
    def full(self) -> bool: ...
    def empty(self) -> bool: ...
    def put_nowait(self, item: LogPage | None) -> None: ...
    def discard_nowait(self) -> LogPage | None: ...
    async def get(self) -> LogPage | None: ...


@dataclass(frozen=True)
class LogDiagnostics:
    counter: Callable[[str, int], QueueCounter]
    lock: Callable[[str], asyncio.Lock]
    outbox: Callable[[str, int], SubscriptionQueue]
    bind_async: Callable[[], None]
