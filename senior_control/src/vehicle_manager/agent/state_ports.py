"""Read-only projection inputs and per-instance original value constructors.

These are consumption shapes, never replacements for IPC or motion values.
"""

from collections.abc import Callable, Sequence
from dataclasses import dataclass
from typing import Any, Protocol

from senior_contracts.navigation import RouteProgress
from senior_contracts.wire import RobotPosePayload, ScanPointPayload

from vehicle_manager.tasks.executor import TaskExecutor
from vehicle_manager.tasks.models import ExecutionContext
from vehicle_manager.tasks.ports import MapReference


class ModeReading(Protocol):
    @property
    def value(self) -> str: ...


class MotionReading(Protocol):
    @property
    def mode(self) -> ModeReading: ...
    @property
    def reason(self) -> str: ...
    @property
    def task_id(self) -> str | None: ...
    @property
    def estop_revision(self) -> int: ...
    @property
    def fault_revision(self) -> int: ...
    @property
    def allowed_actions(self) -> tuple[str, ...]: ...


class TwistReading(Protocol):
    @property
    def vx(self) -> float: ...
    @property
    def vy(self) -> float: ...
    @property
    def wz(self) -> float: ...


class WaypointReading(Protocol):
    @property
    def id(self) -> str: ...
    @property
    def map_ref(self) -> MapReference: ...
    @property
    def status(self) -> str: ...


class BodyReading(Protocol):
    @property
    def average(self) -> TwistReading | None: ...
    @property
    def qualified(self) -> bool: ...
    @property
    def computed_steady(self) -> float: ...
    @property
    def valid_until_steady(self) -> float: ...


class ObservationReading(Protocol):
    @property
    def status(self) -> str: ...
    @property
    def last_sampled_steady(self) -> float | None: ...
    def model_dump(self) -> dict[str, Any]: ...


class RuntimeReading(Protocol):
    @property
    def boot_id(self) -> str: ...
    @property
    def estop_revision(self) -> int: ...
    @property
    def fault_revision(self) -> int: ...
    @property
    def sampled_steady(self) -> float: ...
    @property
    def mode(self) -> str: ...
    @property
    def reason(self) -> str: ...
    @property
    def task_id(self) -> str | None: ...
    @property
    def stationary(self) -> bool: ...
    @property
    def allowed_actions(self) -> Sequence[str]: ...
    @property
    def body_reference(self) -> Any: ...
    @property
    def confirmed_estop_status(self) -> str: ...
    @property
    def wheel_linear_mps(self) -> float | None: ...
    @property
    def evidence_stamp_steady(self) -> float | None: ...
    @property
    def evidence_deadline_steady(self) -> float | None: ...


class StateReading(Protocol):
    @property
    def localized(self) -> bool: ...
    @property
    def map_ref(self) -> MapReference | None: ...
    @property
    def map_generation(self) -> str | None: ...
    @property
    def map_grid_id(self) -> str | None: ...
    @property
    def localization_generation(self) -> str | None: ...
    @property
    def execution_status(self) -> str: ...
    @property
    def route_progress(self) -> RouteProgress | None: ...
    @property
    def navigation_ready(self) -> bool: ...
    @property
    def robot_pose(self) -> RobotPosePayload | None: ...
    @property
    def navigation_block_reason(self) -> str | None: ...
    @property
    def scan_points(self) -> tuple[ScanPointPayload, ...]: ...
    @property
    def manual_driving(self) -> bool: ...
    @property
    def manual_authority(self) -> dict[str, Any] | None: ...
    @property
    def manual_protocol_version(self) -> int: ...
    @property
    def runtime_observation(self) -> ObservationReading | None: ...
    @property
    def motion_runtime(self) -> RuntimeReading | None: ...
    def for_tasks(self, connected: bool) -> ExecutionContext: ...


class StatePort(Protocol):
    async def read(self) -> StateReading: ...


@dataclass(frozen=True)
class ProjectionPorts:
    observation: Callable[..., ObservationReading]
    motion: Callable[..., MotionReading]
    mode: Callable[[str], ModeReading]
    estop_mode: ModeReading


@dataclass(frozen=True)
class SnapshotPorts:
    frame: Callable[..., dict[str, object]]
    observation: Callable[..., ObservationReading]
    error: type[Any]


class SnapshotNavigation(Protocol):
    @property
    def executor(self) -> TaskExecutor: ...
    async def execution_view(self, execution_id: str) -> dict[str, Any]: ...
